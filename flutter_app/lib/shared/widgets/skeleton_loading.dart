/// A skeleton list tile (for student/class/event lists).
class SkeletonListTile extends StatelessWidget {
  final bool showAvatar;

  const SkeletonListTile({super.key, this.showAvatar = true});

  @override
  Widget build(BuildContext context) {
    return Shimmer.fromColors(
      baseColor: Colors.grey[300]!,
      highlightColor: Colors.grey[100]!,
      child: Padding(
        padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 12),
        child: Row(
          children: [
            if (showAvatar) ...[
              Container(
                width: 44,
                height: 44,
                decoration: const BoxDecoration(
                  color: Colors.white,
                  shape: BoxShape.circle,
                ),
              ),
              const SizedBox(width: 12),
            ],
            Expanded(
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Container(
                    width: double.infinity,
                    height: 14,
                    decoration: BoxDecoration(
                      color: Colors.white,
                      borderRadius: BorderRadius.circular(4),
                    ),
                  ),
                  const SizedBox(height: 8),
                  Container(
                    width: 160,
                    height: 12,
                    decoration: BoxDecoration(
                      color: Colors.white,
                      borderRadius: BorderRadius.circular(4),
                    ),
                  ),
                ],
              ),
            ),
          ],
        ),
      ),
    );
  }
}

/// A full-screen skeleton for dashboard loading.
class SkeletonDashboard extends StatelessWidget {
  const SkeletonDashboard({super.key});

  @override
  Widget build(BuildContext context) {
    return SingleChildScrollView(
      padding: const EdgeInsets.all(16),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          // Welcome card skeleton
          const SkeletonBox(width: double.infinity, height: 100),
          const SizedBox(height: 16),

          // Stat cards row
          Row(
            children: const [
              Expanded(child: SkeletonStatCard()),
              SizedBox(width: 12),
              Expanded(child: SkeletonStatCard()),
            ],
          ),
          const SizedBox(height: 12),
          Row(
            children: const [
              Expanded(child: SkeletonStatCard()),
              SizedBox(width: 12),
              Expanded(child: SkeletonStatCard()),
            ],
          ),
          const SizedBox(height: 24),

          // Section header
          const SkeletonBox(width: 140, height: 18),
          const SizedBox(height: 12),

          // List items
          ...List.generate(4, (_) => const SkeletonListTile()),
        ],
      ),
    );
  }
}

/// A skeleton for a simple list page.
class SkeletonListPage extends StatelessWidget {
  final int itemCount;
  final bool showAvatar;

  const SkeletonListPage({
    super.key,
    this.itemCount = 8,
    this.showAvatar = true,
  });

  @override
  Widget build(BuildContext context) {
    return ListView.builder(
      padding: const EdgeInsets.symmetric(vertical: 8),
      itemCount: itemCount,
      itemBuilder: (_, __) => SkeletonListTile(showAvatar: showAvatar),
    );
  }
}

